const assert=require('node:assert/strict');
const S=require('../dist/starboard.js');
const hour=3600000,start=100000000;
let raw=null,fail=false;
const storage={getItem:()=>raw,setItem:(k,v)=>{if(fail)throw Error('quota');raw=v}};
assert.equal(S.idleStatus(S.ensureIdle(storage,start),start+hour).unlocked,false);
S.claimVictory(storage,1,'我方勝利',start);
assert.equal(S.idleStatus(S.load(storage),start+hour-1).amount,0);
assert.equal(S.claimIdle(storage,start+hour*2.5).amount,10);
assert.equal(S.claimIdle(storage,start+hour*2.5).amount,0);
assert.equal(S.claimIdle(storage,start+hour*3).amount,5);
assert.equal(S.claimIdle(storage,start+hour).amount,0);
assert.equal(S.claimIdle(storage,start+hour*30).amount,60);
assert.equal(S.claimIdle(storage,start+hour*30).amount,0);
const before=raw;fail=true;
assert.throws(()=>S.claimIdle(storage,start+hour*31),/quota/);
assert.equal(raw,before);fail=false;
assert.equal(S.claimIdle(storage,start+hour*31).amount,5);
const state=S.load(storage);S.purchase(storage,state,[S.nodes[0].id]);
assert.deepEqual(S.load(storage).idle,state.idle);
S.claimVictory(storage,2,'我方勝利',start+hour*32);
assert.deepEqual(S.load(storage).idle,state.idle);
raw=JSON.stringify({...S.empty(),firstClears:[1]});
assert.equal(S.ensureIdle(storage,start).idle.since,start);
assert.equal(S.ensureIdle(storage,start+hour).idle.since,start);
assert.equal(S.claimIdle(storage,start+hour).amount,5);
assert.throws(()=>S.validate({...S.empty(),idle:{since:-1}}));
